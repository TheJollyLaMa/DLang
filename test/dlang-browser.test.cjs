async function setup(t,{width=1280,reducedMotion='no-preference',scheduled=false,eligible=true,microphone=false}={}) {
  let rosterCalls=0;
  const server=createServer({fetchRoster:async()=>{rosterCalls++;return {contributors:[{github:'fixture',walletAddress:eligible?ADDRESS:'0x'+'9'.repeat(40)}]};}});
  server.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
  const base=`http://127.0.0.1:${server.address().port}`;
  const browser=await chromium.launch({headless:true,args:microphone?['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']:[]});
  t.after(async()=>{await browser.close();await new Promise(r=>server.close(r));});
  const context=await browser.newContext({viewport:{width,height:1000},reducedMotion,hasTouch:width===375});
  if(microphone)await context.grantPermissions(['microphone'],{origin:base});
  const external=[],errors=[];
  await context.route('**/*',route=>{
    if(route.request().url().startsWith(base+'/'))return route.continue();
    external.push(route.request().url());return route.abort();
  });
  if(scheduled)await context.route('**/dlang/round.json',route=>route.fulfill({json:config}));
  const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
  await page.clock.install({time:new Date(START-60000)});
  await page.addInitScript(address=>{
    window.__walletRequests=[];
    const provider={request:async({method})=>{
      window.__walletRequests.push(method);
      if(method==='eth_requestAccounts')return[address];
      if(method==='eth_chainId')return'0x2105';
      throw Error('Forbidden wallet operation: '+method);
    },on(){},removeListener(){}};
    window.ethers={BrowserProvider:class{constructor(provider){this.provider=provider;}}};
    window.addEventListener('eip6963:requestProvider',()=>window.dispatchEvent(new CustomEvent('eip6963:announceProvider',{detail:{info:{uuid:'fixture',name:'Offline fixture',rdns:'org.example.fixture',icon:'data:image/svg+xml,<svg xmlns="http://www.w3.org/2000/svg"/>'},provider}})));
  },ADDRESS);
  await page.goto(base+'/dlang.html');
  await openTool(page,'week');
  await page.locator('#study-scene [data-target]').first().waitFor();
  await page.locator('decent-header wallet-connect #connect').waitFor();
  return{page,context,base,external,errors,rosterCalls:()=>rosterCalls};
}
